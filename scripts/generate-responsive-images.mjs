import { execFile } from 'node:child_process';
import { mkdir, readdir, stat, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

const execFileAsync = promisify(execFile);
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(projectRoot, 'public');
const generatedDataFile = path.join(
    projectRoot,
    'src/data/responsive-images.generated.ts'
);

const collections = [
    { directory: 'photography', widths: [320, 640, 1280] },
    { directory: 'arts', widths: [640, 960, 1920] },
];

const manifest = {};
const conversionTasks = [];
const inefficientVariants = new Set();

function numericFileSort(a, b) {
    return Number.parseInt(a, 10) - Number.parseInt(b, 10);
}

for (const collection of collections) {
    const sourceDirectory = path.join(publicDir, collection.directory);
    const outputDirectory = path.join(publicDir, 'responsive', collection.directory);
    await mkdir(outputDirectory, { recursive: true });

    const filenames = (await readdir(sourceDirectory))
        .filter((filename) => filename.endsWith('.webp'))
        .sort(numericFileSort);

    for (const filename of filenames) {
        const sourcePath = path.join(sourceDirectory, filename);
        const sourceUrl = `/${collection.directory}/${filename}`;
        const { stdout } = await execFileAsync('magick', [
            'identify',
            '-format',
            '%w %h',
            sourcePath,
        ]);
        const [width, height] = stdout.trim().split(/\s+/).map(Number);
        const basename = path.parse(filename).name;
        const variants = collection.widths
            .filter((targetWidth) => targetWidth < width)
            .map((targetWidth) => {
                const outputFilename = `${basename}-${targetWidth}.webp`;
                const outputPath = path.join(outputDirectory, outputFilename);

                conversionTasks.push({
                    sourcePath,
                    outputPath,
                    sourceUrl,
                    targetWidth,
                });

                return {
                    src: `/responsive/${collection.directory}/${outputFilename}`,
                    width: targetWidth,
                };
            });

        manifest[sourceUrl] = { width, height, variants };
    }
}

let nextTaskIndex = 0;
const workerCount = Math.min(4, conversionTasks.length);

async function runWorker() {
    while (nextTaskIndex < conversionTasks.length) {
        const task = conversionTasks[nextTaskIndex];
        nextTaskIndex += 1;

        await execFileAsync('magick', [
            task.sourcePath,
            '-auto-orient',
            '-filter',
            'Lanczos',
            '-resize',
            `${task.targetWidth}x>`,
            '-define',
            'webp:lossless=true',
            task.outputPath,
        ]);

        const [sourceStats, outputStats] = await Promise.all([
            stat(task.sourcePath),
            stat(task.outputPath),
        ]);

        if (outputStats.size >= sourceStats.size) {
            inefficientVariants.add(`${task.sourceUrl}:${task.targetWidth}`);
            await unlink(task.outputPath);
            process.stdout.write(
                `kept smaller original ${task.sourceUrl} instead of ${task.targetWidth}px variant\n`
            );
        } else {
            process.stdout.write(`generated ${task.sourceUrl} @ ${task.targetWidth}px\n`);
        }
    }
}

await Promise.all(Array.from({ length: workerCount }, () => runWorker()));

for (const [sourceUrl, metadata] of Object.entries(manifest)) {
    metadata.variants = metadata.variants.filter(
        (variant) => !inefficientVariants.has(`${sourceUrl}:${variant.width}`)
    );
}

const generatedModule = `// Generated by npm run images:responsive. Do not edit manually.\n\nexport interface ResponsiveImageVariant {\n    src: string;\n    width: number;\n}\n\nexport interface ResponsiveImageMetadata {\n    width: number;\n    height: number;\n    variants: readonly ResponsiveImageVariant[];\n}\n\nexport const responsiveImages: Record<string, ResponsiveImageMetadata> = ${JSON.stringify(manifest, null, 4)};\n`;

await writeFile(generatedDataFile, generatedModule);
process.stdout.write(`wrote ${path.relative(projectRoot, generatedDataFile)}\n`);
